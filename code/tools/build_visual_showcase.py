def reward_control_endpoints() -> None:
    control = read_csv("ablation/reward_control_long_table.csv")
    mmgag = control[control["benchmark"].isin(["mmgag_aerial", "mmgag_ground", "mmgag_text"])]
    grouped = mmgag.groupby("run")["sr"].mean().reset_index()
    name_map = {
        "reward_external_only_seed321_t480k": "External only",
        "reward_intrinsic_only_seed321_t480k": "Intrinsic only",
        "reward_intrinsic_no_decay_seed321_t480k": "Ext+Int, no gate/PBRS",
    }
    grouped["label"] = grouped["run"].map(name_map).fillna(grouped["run"])

    gate = read_csv("ablation/reward_gate_type_mmgag_only_table_with_linear.csv")
    ours = float(gate[gate["value"].eq("linear_0.405_pb")]["mmgag_mean_sr"].iloc[0])
    rows = pd.concat(
        [
            grouped[["label", "sr"]].rename(columns={"sr": "mmgag_mean_sr"}),
            pd.DataFrame([{"label": "Full reward (ours)", "mmgag_mean_sr": ours}]),
        ],
        ignore_index=True,
    ).sort_values("mmgag_mean_sr", ascending=True)

    fig, ax = plt.subplots(figsize=(8.5, 4.9))
    colors = ["#B8BCC7"] * len(rows)
    colors[list(rows["label"]).index("Full reward (ours)")] = PALETTE["Ours"]
    ax.barh(rows["label"], rows["mmgag_mean_sr"], color=colors, height=0.58)
    ax.set_xlim(0, 0.66)
