def finish_ax(ax: plt.Axes, grid_axis: str = "y") -> None:
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.spines["left"].set_color("#D7DCE3")
    ax.spines["bottom"].set_color("#D7DCE3")
    if grid_axis:
        ax.grid(axis=grid_axis, alpha=0.25, color="#9AA4B2", linewidth=0.8)
    ax.set_axisbelow(True)


def save_figure(fig: plt.Figure, stem: str) -> None:
    fig.tight_layout()
    png_path = FIG_DIR / f"{stem}.png"
    svg_path = FIG_DIR / f"{stem}.svg"
    fig.savefig(png_path, dpi=220, bbox_inches="tight")
    fig.savefig(svg_path, bbox_inches="tight")
    strip_trailing_whitespace(svg_path)
    plt.close(fig)


def strip_trailing_whitespace(path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    cleaned = "\n".join(line.rstrip() for line in text.splitlines()) + "\n"
    path.write_text(cleaned, encoding="utf-8")


def label_bars(ax: plt.Axes, fmt: str = "{:.3f}", dx: float = 0.006) -> None:
    for patch in ax.patches:
        width = patch.get_width()
        if not np.isfinite(width):
            continue
        ax.text(
            width + dx,
            patch.get_y() + patch.get_height() / 2,
            fmt.format(width),
            va="center",
            ha="left",
            fontsize=9,
            color="#111827",
        )


def benchmark_overview_dashboard() -> None:
    df = read_csv("main_benchmark/paper_baseline_compare_table.csv")
    df["method_clean"] = df["method"].map(normalize_method)
    pair = df[df["method_clean"].isin(["Ours", "GOMAA-Geo"])].copy()
    pivot = pair.pivot_table(
        index="benchmark", columns="method_clean", values="success_ratio", aggfunc="first"
    ).dropna()
    pivot["gain"] = pivot["Ours"] - pivot["GOMAA-Geo"]
    pivot = pivot.sort_values("gain", ascending=True)

    ultra = read_csv("ultra_long/ultra_long_v2_summary.csv")
    ultra["method_clean"] = ultra["method_key"].map(normalize_method)
    ultra_ours = ultra[ultra["method_key"].eq("anchor0624")]["success_ratio"].mean()
    ultra_gomaa = ultra[ultra["method_key"].eq("gomaa")]["success_ratio"].mean()

    fig = plt.figure(figsize=(14, 8))
    gs = fig.add_gridspec(2, 4, height_ratios=[1.1, 3.0])
    cards = [
        ("Shared Mean SR", pivot["Ours"].mean(), "#0077BB"),
        ("GOMAA Mean SR", pivot["GOMAA-Geo"].mean(), "#EE7733"),
        ("Mean Gain", pivot["gain"].mean(), "#009988"),
        ("Long-range Gain", ultra_ours - ultra_gomaa, "#8F5D00"),
    ]
    for i, (title, value, color) in enumerate(cards):
        ax = fig.add_subplot(gs[0, i])
        ax.set_axis_off()
        card = FancyBboxPatch(
            (0.02, 0.05),
            0.96,
            0.85,
            boxstyle="round,pad=0.025,rounding_size=0.045",
            linewidth=1.2,
            edgecolor="#E5E7EB",
            facecolor="#F8FAFC",
        )
        ax.add_patch(card)
        ax.text(0.08, 0.70, title, fontsize=12, color="#4B5563", transform=ax.transAxes)
        sign = "+" if "Gain" in title and value >= 0 else ""
        ax.text(
            0.08,
            0.30,
            f"{sign}{value:.3f}",
            fontsize=28,
            fontweight="bold",
            color=color,
            transform=ax.transAxes,
        )

    ax = fig.add_subplot(gs[1, :])
    y = np.arange(len(pivot))
    ax.barh(y - 0.17, pivot["GOMAA-Geo"], height=0.34, color=PALETTE["GOMAA-Geo"], label="GOMAA-Geo")
    ax.barh(y + 0.17, pivot["Ours"], height=0.34, color=PALETTE["Ours"], label="Ours")
    ax.set_yticks(y)
    ax.set_yticklabels([x.replace("_", " ") for x in pivot.index])
    ax.set_xlim(0, max(0.75, pivot[["Ours", "GOMAA-Geo"]].max().max() + 0.08))
    ax.set_xlabel("Success rate")
    ax.set_title("Ours leads GOMAA-Geo across the shared benchmark suite")
    ax.legend(loc="lower right", frameon=False)
    for idx, (_, row) in enumerate(pivot.iterrows()):
        ax.text(
            row["Ours"] + 0.008,
            idx + 0.17,
            f"+{row['gain']:.3f}",
            va="center",
            fontsize=8.5,
            color="#0077BB",
            fontweight="bold",
        )
    finish_ax(ax)
    save_figure(fig, "benchmark_overview_dashboard")


def mmgag_modality_sr() -> None:
    df = read_csv("main_benchmark/paper_baseline_compare_table.csv")
    df["method_clean"] = df["method"].map(normalize_method)
    rows = df[df["benchmark"].isin(["mmgag_aerial", "mmgag_ground", "mmgag_text"])].copy()
    rows["target"] = rows["benchmark"].map(
        {"mmgag_aerial": "Aerial goal", "mmgag_ground": "Ground goal", "mmgag_text": "Text goal"}
    )

    airloc_path = TABLE_DIR / "main_benchmark" / "airloc_mmgag_aerial_table_row.csv"
    if airloc_path.exists():
        airloc = pd.read_csv(airloc_path).iloc[0]
        rows = pd.concat(
            [
                rows,
                pd.DataFrame(
                    [
                        {
                            "method_clean": "AiRLoc",
                            "target": "Aerial goal",
                            "success_ratio": float(airloc["sr"]),
                        }
                    ]
                ),
            ],
            ignore_index=True,
        )

    methods = ["Ours", "GOMAA-Geo", "AiRLoc", "Random", "DiT-AGL"]
    targets = ["Aerial goal", "Ground goal", "Text goal"]
    fig, ax = plt.subplots(figsize=(10.5, 5.8))
    x = np.arange(len(targets))
    width = 0.15
    for i, method in enumerate(methods):
        values = []
        for target in targets:
            hit = rows[(rows["target"].eq(target)) & (rows["method_clean"].eq(method))]
            values.append(float(hit["success_ratio"].iloc[0]) if len(hit) else np.nan)
        offset = (i - (len(methods) - 1) / 2) * width
        bars = ax.bar(
            x + offset,
            values,
            width=width,
            label=method,
            color=PALETTE.get(method, "#94A3B8"),
            alpha=1.0 if method == "Ours" else 0.85,
        )
        for bar, value in zip(bars, values):
            if np.isfinite(value):
                ax.text(
                    bar.get_x() + bar.get_width() / 2,
                    value + 0.012,
                    f"{value:.3f}",
                    ha="center",
                    va="bottom",
                    fontsize=8,
                    rotation=90 if method in ["Random", "DiT-AGL"] else 0,
                )
    ax.set_xticks(x)
    ax.set_xticklabels(targets)
    ax.set_ylim(0, 0.72)
    ax.set_ylabel("Success rate")
    ax.set_title("MM-GAG cross-modal evaluation: strongest gains on all target forms")
    ax.legend(ncol=5, frameon=False, loc="upper center", bbox_to_anchor=(0.5, -0.10))
    finish_ax(ax)
    save_figure(fig, "mmgag_modality_sr")


