def copy_media() -> dict[str, int]:
    counts: dict[str, int] = {}

    copy_specs = [
        (SOURCE_TRAJECTORY / "gif", FIG_DIR / "trajectories" / "gifs", ["*.gif"]),
        (SOURCE_TRAJECTORY / "comparison_png", FIG_DIR / "trajectories" / "comparison_png", ["*.png"]),
        (SOURCE_TRAJECTORY / "static_png", FIG_DIR / "trajectories" / "static_png", ["*.png"]),
        (SOURCE_REWARD / "figures", FIG_DIR / "reward_story", ["*.png", "*.svg"]),
        (SOURCE_REWARD / "gifs", FIG_DIR / "reward_story" / "gifs", ["*.gif"]),
    ]

    for src_dir, dst_dir, patterns in copy_specs:
        copied = 0
        if src_dir.exists():
            dst_dir.mkdir(parents=True, exist_ok=True)
            for pattern in patterns:
                for src in sorted(src_dir.glob(pattern)):
                    dst = dst_dir / src.name
                    shutil.copy2(src, dst)
                    if dst.suffix.lower() == ".svg":
                        strip_trailing_whitespace(dst)
                    copied += 1
        counts[str(dst_dir.relative_to(ROOT))] = copied

    dataset_specs = [
        ROOT / "results" / "figures" / "chapter2_dataset" / "figure_dataset_overview.png",
        ROOT / "results" / "figures" / "chapter2_dataset" / "chapter2_typical_dataset_scene_examples.png",
        ROOT / "results" / "figures" / "chapter3_method" / "figure3_1_method_overview_revised.png",
        ROOT / "results" / "figures" / "chapter4_trajectories" / "figure4_x_anchor_typical_c4_c6_c8.png",
        ROOT / "results" / "figures" / "chapter4_trajectories" / "figure4_y_three_method_hardcase_revised.png",
    ]
    copied = 0
    for src in dataset_specs:
        if src.exists():
            shutil.copy2(src, FIG_DIR / "dataset" / src.name)
            copied += 1
    counts[str((FIG_DIR / "dataset").relative_to(ROOT))] = copied
    return counts


def write_manifest(media_counts: dict[str, int]) -> None:
    files = sorted(
        str(p.relative_to(ROOT)).replace("\\", "/")
        for p in FIG_DIR.rglob("*")
        if p.is_file() and p.name not in {"showcase_manifest.json", "README.md"}
    )
    manifest = {
        "generated_by": "code/tools/build_visual_showcase.py",
        "figure_root": str(FIG_DIR.relative_to(ROOT)).replace("\\", "/"),
        "file_count": len(files),
        "media_counts": media_counts,
        "files": files,
    }
    (FIG_DIR / "showcase_manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
    )


