def trajectory_statistics() -> None:
    df = read_csv("main_benchmark/trajectory_records.csv")
    df["method_clean"] = df["method"].map(normalize_method)
    summary = (
        df.groupby(["method_clean", "distance"])
        .agg(success_rate=("success", "mean"), mean_detour=("detour_steps", "mean"), n=("success", "size"))
        .reset_index()
    )

    fig, axes = plt.subplots(1, 2, figsize=(13, 5.2))
    for method in ["Ours", "GOMAA-Geo", "GeoExplorer"]:
        hit = summary[summary["method_clean"].eq(method)].sort_values("distance")
        if hit.empty:
            continue
        axes[0].plot(
            hit["distance"],
            hit["success_rate"],
            marker="o",
            linewidth=2.7 if method == "Ours" else 2.0,
            color=PALETTE.get(method, "#64748B"),
            label=method,
        )
        axes[1].plot(
            hit["distance"],
            hit["mean_detour"],
            marker="o",
            linewidth=2.7 if method == "Ours" else 2.0,
            color=PALETTE.get(method, "#64748B"),
            label=method,
        )
    axes[0].set_title("Qualitative case bank: success by distance")
    axes[0].set_xlabel("Distance")
    axes[0].set_ylabel("Success rate")
    axes[0].set_ylim(0, 1.02)
    axes[1].set_title("Qualitative case bank: detour steps")
    axes[1].set_xlabel("Distance")
    axes[1].set_ylabel("Mean detour steps")
    for ax in axes:
        finish_ax(ax)
    axes[0].legend(frameon=False, loc="lower right")
    save_figure(fig, "trajectory_statistics")

    pivot = summary.pivot(index="method_clean", columns="distance", values="success_rate").reindex(
        ["Ours", "GOMAA-Geo", "GeoExplorer"]
    )
    fig, ax = plt.subplots(figsize=(7.8, 3.8))
    im = ax.imshow(pivot.values, cmap="YlGnBu", vmin=0, vmax=1)
    ax.set_xticks(np.arange(pivot.shape[1]))
    ax.set_xticklabels([f"C={int(c)}" for c in pivot.columns])
    ax.set_yticks(np.arange(pivot.shape[0]))
    ax.set_yticklabels(pivot.index)
    for i in range(pivot.shape[0]):
        for j in range(pivot.shape[1]):
            value = pivot.iloc[i, j]
            ax.text(j, i, f"{value:.2f}", ha="center", va="center", color="white" if value > 0.55 else "#111827")
    fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04, label="Success rate")
    ax.set_title("Trajectory visualization bank coverage")
    save_figure(fig, "trajectory_success_heatmap")

    fig, ax = plt.subplots(figsize=(9, 5))
    methods = ["Ours", "GOMAA-Geo", "GeoExplorer"]
    data = [df[df["method_clean"].eq(m)]["detour_steps"].clip(upper=12).values for m in methods]
    bp = ax.boxplot(data, tick_labels=methods, patch_artist=True, showfliers=False)
    for patch, method in zip(bp["boxes"], methods):
        patch.set_facecolor(PALETTE.get(method, "#CBD5E1"))
        patch.set_alpha(0.75)
    ax.set_ylabel("Detour steps, clipped at 12")
    ax.set_title("Path efficiency distribution over 2,205 recorded trajectories")
    finish_ax(ax)
    save_figure(fig, "trajectory_detour_distribution")


